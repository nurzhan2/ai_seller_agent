def _catalog_block(kb: KnowledgeBase) -> str:
    """Справочник зон для модели. Без цен — цены только через инструмент."""
    lines: list[str] = ["СПРАВОЧНИК ЗОН (цены тут намеренно отсутствуют)", ""]
    for zone in kb.catalog.zones:
        capacity = (
            f"до {zone.capacity.value} чел."
            if zone.capacity.is_resolved()
            else "вместимость не подтверждена — точную цифру не называй"
        )
        title = zone.name
        if zone.display_name_alt:
            # Клиент называет зону иначе, чем в каталоге (напр. заказчик сам
            # пишет «Баня Замок Рыцаря» вместо «Рыцарская») — агент должен
            # узнавать оба варианта и отвечать словами собеседника.
            title = f"{zone.name} (также встречается как «{zone.display_name_alt}»)"
        lines.append(f"[{zone.id}] {title} — {capacity}")
        lines.append(f"  {' '.join(zone.description.split())}")
        if zone.includes:
            lines.append(f"  Входит: {', '.join(zone.includes)}")
        lines.append("")

    lines.append("ЧАСТЫЕ ВОПРОСЫ — что мы знаем")
    for entry in kb.catalog.knowledge:
        # Записи без ответа сюда НЕ попадают намеренно. Это внутренние открытые
        # вопросы аудита: они содержат номера диалогов, id вопросов и суммы из
        # спорных находок (например «продавалась за 2500₽/час»). Модели они не
        # дают никакой возможности ответить, зато показывают ей числа, которые
        # она может принять за тариф. Всё, чего нет в базе, и так покрыто общим
        # правилом «нет в базе — уточню у менеджера».
        if not entry.answer:
            continue
        mark = "подтверждено" if entry.confidence == "confirmed" else "из переписок"
        lines.append(f"— {entry.question_topic} ({mark}): {' '.join(entry.answer.split())}")
    return "\n".join(lines)


def build_now_block(now: Optional[datetime] = None) -> str:
    """Блок «Сейчас:» — единственный источник текущей даты для модели.

    ЗАВТРАШНЯЯ ДАТА ПОСЧИТАНА ЗДЕСЬ, А НЕ ОСТАВЛЕНА МОДЕЛИ. Инцидент
    2026-09-01: блок доехал и был верным, модель взяла из него ВРЕМЯ
    («сейчас 22:53» — точно), а дату пересчитала сама и написала клиенту
    «завтра, 1 сентября» в день, который и был 1 сентября. То есть ломается
    не доставка даты, а арифметика поверх неё, — значит арифметику надо
    убрать. «Завтра» теперь не выводится, а читается.

    Дата названа ДВАЖДЫ, в начале и в конце блока. Блок идёт последним и не
    кешируется, так что повтор ничего не стоит; вклеить её ещё и в текст
    правил нельзя — `static_part` лежит префиксом перед кешируемым каталогом
    (см. build_system_prompt), и правка на каждом ходу выключила бы кеш.
    """
    # Приводим к МСК ТЕМ ЖЕ способом, что и describe_now: иначе naive или
    # UTC-время даст дату на сутки назад — контейнер живёт в UTC.
    moment = (now or moscow_now()).astimezone(MOSCOW_TZ)
    tomorrow = moment + timedelta(days=1)
    today_s = f"{moment:%d.%m.%Y} ({WEEKDAYS_RU[moment.weekday()]})"
    tomorrow_s = f"{tomorrow:%d.%m.%Y} ({WEEKDAYS_RU[tomorrow.weekday()]})"
    return (
        f"Сейчас: {describe_now(now)}.\n"
        f"СЕГОДНЯ — {today_s}.\n"
        f"ЗАВТРА — {tomorrow_s}.\n"
        "Это ЕДИНСТВЕННЫЙ источник сегодняшней даты. Не полагайся на свои "
        "представления о текущем числе — считай «сегодня», «завтра» и любые "
        "относительные даты только отсюда.\n"
        "Ничего не прибавляй и не вычитай сам: обе даты выше уже посчитаны. "
        "Прежде чем написать в ответе слово «сегодня» или «завтра» рядом с "
        "числом, сверь это число со строками выше — оно обязано совпасть.\n"
        f"Повторю, потому что на этом уже ошибались: сегодня {today_s}, "
        f"завтра {tomorrow_s}."
    )


def build_system_prompt(
    kb: KnowledgeBase, now: Optional[datetime] = None
) -> list[dict[str, Any]]:
    """Системный промт блоками, каталог помечен для кеширования.

    ТЕКУЩАЯ ДАТА — ОТДЕЛЬНЫМ, НЕКЕШИРУЕМЫМ БЛОКОМ И ПОСЛЕДНЕЙ. Это не
    косметика:

      * блок каталога помечен `cache_control` и обязан оставаться неизменным
        байт в байт, иначе кеш промахивается на каждом ходу. Дата меняется
        каждую минуту — подмешать её в кешируемый блок значит выключить кеш;
      * статическая часть не меняется по той же причине, поэтому дата не
        вклеивается и в текст правил;
      * последней — потому что это самый свежий факт хода, и модель должна
        видеть его после правил, а не до них.

    Без этого блока модель берёт дату из собственных представлений. Именно
    так 31 августа стало сначала «завтра», потом «сегодня», а потом «уже
    прошло» — см. AVAILABILITY_AND_DATES.
    """
    static_part = "\n\n".join(
        [ROLE_AND_TONE, HARD_PROHIBITIONS, STATUS_HANDLING, AVAILABILITY_AND_DATES, SCENARIO]
    )
    return [
        {"type": "text", "text": static_part},
        {
            "type": "text",
            "text": _catalog_block(kb),
            "cache_control": {"type": "ephemeral"},
        },
        {"type": "text", "text": build_now_block(now)},
    ]


