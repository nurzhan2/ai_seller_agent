"""Один вопрос в сообщении — правилом рубежа, а не пожеланием промта.

ЗАЧЕМ ЭТОТ МОДУЛЬ СУЩЕСТВУЕТ. Требование «один вопрос за сообщение» жило
только в двух местах, и оба ничего не гарантировали: строка системного
промта (app/agent/prompts.py — модель исполняет её через раз) и правило
офлайн-харнесса `too_many_questions` (app/quality/asserts.py — оно считает
нарушения ПОСЛЕ прогона и клиента ни от чего не защищает). Замер
2026-09-02 дал 9% ответов с несколькими вопросами
(docs/quality/tool_forcing_probe.md), а заказчик после двух недель в проде
назвал допрос главной причиной, по которой клиенты уходят звонить вместо
того, чтобы бронировать.

ПОЧЕМУ ОБРЕЗКА, А НЕ ПЕРЕСПРОС МОДЕЛИ. Второй вариант — отправить модели
ответ обратно со словами «перепиши одним вопросом» — стоит лишнего хода
(деньги и секунды на каждом срабатывании) и не даёт гарантии: модель может
снова вернуть два вопроса. Обрезка детерминированна, проверяется тестом и
не может не сработать.

ЧТО ИМЕННО ОБРЕЗАЕТСЯ — И ПОЧЕМУ ИМЕННО ТАК. Текст режется по началу
ВТОРОГО вопросительного предложения, то есть остаётся его префикс. Это не
«выкусывание» лишних вопросов из середины, и разница принципиальная:
заказчик отдельно предупредил про ответ вида «вопрос — пояснение —
вопрос», где пояснение относится к ВТОРОМУ вопросу. Вырезать вопрос и
оставить пояснение значит отдать клиенту висящий хвост:

    «На какую дату планируете? И на сколько часов? От трёх — это минимум.»
     └─ оставляем ──────────────┘ └─ отсюда режем ─────────────────────┘

Всё, что стоит ПОСЛЕ первого вопроса, но ДО второго, остаётся: это ответ по
существу, ради которого разговор и ведётся («тариф 2000 ₽/час, минимум
3 часа»), и терять его нельзя — иначе рубеж лечил бы допрос молчанием про
деньги, то есть вторую жалобу заказчика из того же письма.
"""

from __future__ import annotations

import re

# Подряд идущие вопросительные знаки — это ОДИН вопрос, а не три: «Правда???»
# Схлопываем до начала счёта, иначе рубеж срабатывал бы на пунктуации и
# резал бы текст, в котором вопрос ровно один.
_REPEATED_MARKS = re.compile(r"\?{2,}")

# Конец предложения: точка/восклицательный/вопросительный/многоточие, за
# которыми идёт пробел или конец текста. Кавычки-ёлочки и скобки после знака
# препинания тоже закрывают предложение («...Рыцарскую»?).
#
# ЧЕГО ЭТО НЕ УМЕЕТ и уметь не обязано: сокращений с точкой внутри («т.е.»,
# «ул.»). Цена ошибки — лишняя граница предложения, то есть обрезка чуть
# раньше или чуть позже; в текстах агента сокращения с точкой не
# встречаются (промт требует живых фраз, а суммы пишутся «2000 ₽»).
_SENTENCE_END = re.compile(r"[.!?…]+[»\"')\]]*(?=\s|$)")


def normalize_question_marks(text: str) -> str:
    """«Правда???» -> «Правда?». Больше ничего не меняет."""
    return _REPEATED_MARKS.sub("?", text or "")


def split_sentences(text: str) -> list[tuple[int, str]]:
    """Предложения как (смещение в исходном тексте, текст предложения).

    Смещения нужны обрезке: она режет ИСХОДНЫЙ текст по позиции, а не
    склеивает предложения заново, — так сохраняются переносы строк и
    двойные пробелы, которыми модель разбивает ответ на абзацы.
    """
    sentences: list[tuple[int, str]] = []
    start = 0
    for match in _SENTENCE_END.finditer(text or ""):
        end = match.end()
        chunk = text[start:end]
        if chunk.strip():
            sentences.append((start + len(chunk) - len(chunk.lstrip()), chunk.strip()))
        start = end
    tail = (text or "")[start:]
    if tail.strip():
        sentences.append((start + len(tail) - len(tail.lstrip()), tail.strip()))
    return sentences


def is_question(sentence: str) -> bool:
    return "?" in sentence


def count_questions(text: str) -> int:
    """Сколько вопросов в тексте — по предложениям, а не по знакам.

    Считать знаки «?» напрямую нельзя: «Правда???» — один вопрос, а не три.
    Зато предложение с вопросительным знаком внутри («Вы про какую баню —
    «Русский стиль», «Гараж» или «Рыцарскую»?») — ровно один вопрос, каким
    бы длинным оно ни было.
    """
    return sum(1 for _, sentence in split_sentences(normalize_question_marks(text)) if is_question(sentence))


def trim_to_one_question(text: str) -> str:
    """Текст, в котором остался ровно один вопрос (или ни одного).

    Возвращает исходный текст без изменений, если вопросов и так не больше
    одного, — рубеж не должен трогать то, что и так в порядке.
    """
    normalized = normalize_question_marks(text or "")
    sentences = split_sentences(normalized)

    seen_question = False
    for offset, sentence in sentences:
        if not is_question(sentence):
            continue
        if not seen_question:
            seen_question = True
            continue
        # Второй вопрос — режем здесь, вместе со всем, что за ним.
        trimmed = normalized[:offset].rstrip()
        # Пустого результата быть не может (первый вопрос стоит левее), но
        # если однажды станет — отдаём исходный текст: пустой ответ клиенту
        # хуже, чем лишний вопрос.
        return trimmed or normalized
    return normalized
