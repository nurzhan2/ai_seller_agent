"""Когда модель ОБЯЗАНА вызвать инструмент, а не рассуждать словами.

ЗАЧЕМ ЭТО СУЩЕСТВУЕТ. DeepSeek вызывает инструменты примерно в половине
ходов — и это его свойство, а не наша ошибка. Промт ни при чём: его
усиливали дважды (2026-08-31 и 2026-09-01), оба раза без результата.

ЧТО ИМЕННО ДЕЛАЕТ `tool_choice` НА DEEPSEEK. Замер 2026-09-02 на живом
`deepseek-v4-pro`, воспроизводится скриптом `scripts/probe_tool_forcing.py`.
Сначала изолированный опыт — один вызов модели, без петли витков, два разных
сообщения клиента по 5 повторов на условие:

    без tool_choice ................................  0 вызовов из 10
    tool_choice {"type": "any"} ....................  1 вызов  из 10
    tool_choice {"type": "tool", "name": ...} ...... 10 вызовов из 10

Отсюда ГЛАВНОЕ, и оно не то, что казалось сначала:

  * `{"type": "any"}` DeepSeek принимает и МОЛЧА ИГНОРИРУЕТ — столько же
    вызовов, сколько без него вовсе. Полагаться на него нельзя;
  * адресное `{"type": "tool", "name": ...}` включает вызов инструмента
    надёжно, НО ИМЯ НЕ ИСПОЛНЯЕТ. В том же опыте перебрали четыре разных
    имени (`resolve_date`, `check_availability`, `get_zones`,
    `calculate_price`) — инструмент звался все 40 раз из 40, а звался
    ИМЕННО ЗАКАЗАННЫЙ лишь 5 раз из 40. На «а цена какая?» с принуждением
    `calculate_price` модель уходила в `find_next_available`.

То есть для DeepSeek имя — это ВЫКЛЮЧАТЕЛЬ, а не выбор. Выбор всё равно
остаётся за моделью.

ПОЧЕМУ ТОГДА ВЫБОР ЗДЕСЬ ВООБЩЕ ЕСТЬ. Три причины, и ни одна не про красоту:

  * послать какое-то имя ПРИДЁТСЯ: «любой инструмент» игнорируется, и другой
    формы включить принуждение у нас нет;
  * раз имя послать всё равно надо, посылать осмысленное строго лучше, чем
    случайное: модель видит его как сильную подсказку. По полному ходу через
    петлю заказанный инструмент звался первым в 16 случаях из 35 — против
    5 из 40 в изолированном опыте, где имя было заведомо не к месту;
  * Anthropic (резервный провайдер, `LLM_FALLBACK_PROVIDER`) имя исполняет
    точно — это его документированное поведение. Живым вызовом здесь НЕ
    проверено: ключ в .env — заглушка `sk-ant-xxxxx`.

ЧТО ЭТО ДАЁТ НА САМОМ ДЕЛЕ. Полный ход через `AgentLoop.run_turn`, 7 случаев
по 5 повторов, каждый случай — со своим контрольным плечом (тот же ход, но
принуждение выключено):

    с принуждением ....... 29 ходов из 35 оперлись на инструмент
    без принуждения ......  3 хода  из 35

Разница и есть смысл этой правки. Но 29 из 35 — НЕ гарантия, и это важнее
самой цифры: на одном из случаев («Есть окошко сегодня?») замер дал 0 из 5,
а тот же случай через час — 5 из 5. Поведение чужого слоя совместимости
меняется во времени, и строить на нём защиту клиента нельзя. Защищает
последний рубеж в app/agent/loop.py; принуждение лишь делает так, чтобы
рубежу было что пропускать.

ЦЕНА ПРИНУЖДАЕТСЯ НЕ ВСЕГДА, И ЭТО ИСПРАВЛЕНИЕ ПО ЗАМЕРУ. Первая редакция
принуждала `calculate_price` на любой вопрос о стоимости. Живой замер того
же дня показал цену такого решения: инструмент требует `zone_id` и `date`,
на голое «а цена какая?» модель выдумывала оба поля, получала `needs_input`
и следом спрашивала у клиента всё разом. Доля ответов больше чем с одним
вопросом — 18% против 2% без принуждения.

После сужения (зона ИЛИ дата обязаны быть в разговоре) — 11% против 0% на
тех же случаях. Не 2%, и остаток честно виден: он приходится на ветки
занятости, где `check_availability` тоже требует зону. Трогать их не стали
намеренно — выдуманная занятость была живым инцидентом, лишний вопрос в
ответе живым инцидентом не был.

ПРИЗНАК ДОСТУПНОСТИ ОБЯЗАТЕЛЕН ВО ВСЕХ ВЕТКАХ, И ЭТО НЕ ПРИДИРКА. Требование
заказчика содержит две части, которые сходятся только так: «относительная
дата без конкретики → resolve_date» и «„Завтра перезвоню“ инструмент дёргать
не должно». В обоих сообщениях есть относительная дата; разводит их только
то, спрашивает ли клиент про запись. Принуждать инструмент на каждую дату в
тексте значило бы ходить в календарь на «завтра перезвоню» и «вчера были у
вас» — лишние вызовы, лишние деньги и разговор, который ведёт себя странно.
Замер это подтвердил: на «завтра перезвоню» инструменты не звались ни разу
из пяти — ровно как задумано.
"""

from __future__ import annotations

import re
from typing import Optional

# Слова, по которым видно, что зона в разговоре УЖЕ названа. Это не полный
# каталог, а корни его категорий и опознавательные слова вариантов внутри
# них: «баня» одна на три бани, «купол» — на три купола. Точный выбор между
# «Русским стилем» и «Гаражом» здесь не нужен — нужен ответ на вопрос
# «клиент уже сказал, о чём речь?».
#
# Держится тестом test_every_zone_in_the_catalogue_is_recognised: он берёт
# зоны из живой базы знаний и проверяет каждую. Появится в каталоге зона
# нового рода — тест упадёт, и это единственный способ не пропустить такое
# молча в модуле, который базу знаний намеренно не импортирует.
ZONE_WORDS = re.compile(
    r"\bбан[ьяию]\w*|\bдомик\w*|\bкупол\w*|\bгриль\w*|\bшат[её]р\w*|"
    r"\bюрт\w*|\bрыцарск\w*|\bзамок\b|\bгараж\w*|\bрусск\w*|"
    r"\bзел[её]н\w*|\bмешк\w*|\bкресл\w*|\bстул\w*",
    re.IGNORECASE,
)

# Спрашивает про цену. Отдельно и ПЕРВЫМ: «сколько стоит на завтра» — это
# про деньги, а календарь подтянется следующим витком, если понадобится.
PRICE_ASK = re.compile(
    r"скольк\w*\s+(?:стоит|будет|выйдет|обойд\w*)|"
    r"\bцен[аыуе]\w*|\bстоимост\w*|\bпочём\b|\bпочем\b|\bпрайс\w*",
    re.IGNORECASE,
)

# Спрашивает про запись/занятость. Это и есть тот самый признак, без
# которого не принуждается ничего.
#
# РУССКАЯ ОСНОВА В РЕГЭКСПЕ — СИСТЕМНАЯ ЛОВУШКА, А НЕ ЧАСТНЫЙ БАГ. Первая
# редакция ловила `\bбронир\w*` и `\bброн[ьяию]\w*` — и не опознавала
# «забронировать», потому что граница слова `\b` съедается приставкой. То
# есть САМОЕ ЧАСТОЕ слово, которым клиент просит бронь, проходило мимо.
# Ровно та же ошибка сидела в `свободн\w*`: краткая форма мужского рода
# «свободен» не начинается на «свободн», а зоны мужского рода у нас четыре
# из десяти (купол, домик, гриль-домик, шатёр).
#
# Поэтому здесь приставки перечислены явно, а формы проверяются тестом
# против набора реальных словоформ, а не «на глаз».
#
# ЗДЕСЬ СЛОВАРЬ ШИРЕ, ЧЕМ В РУБЕЖЕ (app/agent/loop.py), И ЭТО НАМЕРЕННО.
# Цена ошибки разная: лишнее срабатывание ЗДЕСЬ стоит одного вызова
# инструмента, лишнее срабатывание В РУБЕЖЕ — молчания агента там, где он
# мог ответить. Поэтому «окна» (которые в бане сплошь и рядом настоящие
# окна: «вид из окна», «окна выходят на пруд») входят сюда и НЕ входят
# в словарь рубежа.
AVAILABILITY_ASK = re.compile(
    r"\bсвобод(?:ен|ны|на|но|н\w*)|\bосвобод\w*|\bзанят\w*|"
    r"\bокошк\w*|\bокн[оауе]\w*|\bокон\b|есть\s+врем\w*|"
    r"\bзапиш\w*|\bзапис\w*|"
    r"\b(?:за|пере)?брон(?:ь|и|ю|я|е|ир\w*)|\b(?:за)?резерв(?!уар)\w*|"
    r"\bможно\s+(?:ли\s+)?(?:прие\w*|к\s+вам|сегодня|завтра|послезавтра|"
    r"в\s+\w+|на\s+\w+)|"
    r"\bпринима\w*\s+сегодня|\bуспе\w*\s+сегодня",
    re.IGNORECASE,
)

# КОГДА ПРИНУЖДАТЬ НЕЛЬЗЯ, ЧТО БЫ НИ НАШЛОСЬ ОСТАЛЬНОЕ.
#
# Три класса сообщений, где дата и время есть, а идти в календарь не за чем:
#   «завтра перезвоню», «наберу вас в ближайшее время» — обещание клиента
#     позвонить (требование заказчика дословно: инструмент не дёргать);
#   «мы были у вас в субботу в 18:00, спасибо» — прошедший визит;
#   «отмените нашу бронь на 5 сентября в 18:00» — отмена, а не запись.
# Все три до этой правки принуждали check_availability: ветка «дата и время»
# признака записи не спрашивает вовсе.
NOT_A_BOOKING = re.compile(
    r"\bперезвон\w*|\bперезван\w*|\bнаберу\b|\bсвяжусь\b|"
    r"\bотмен[аыеиую]\w*|\bотказ\w*|\bбыл[аи]?\s+у\s+вас|\bбыли\s+у\s+вас",
    re.IGNORECASE,
)

# «Когда ближайшее свободное» — числа клиент не называет, спрашивает нас.
# «в ближайшее ВРЕМЯ» из набора исключено: это оборот про скорость ответа
# («перезвоню в ближайшее время», «напишу в ближайшее время»), а не вопрос о
# календаре. Без этого исключения обещание клиента позвонить включало
# find_next_available.
NEAREST_ASK = re.compile(
    r"\bближайш\w*\b(?!\s+врем)|когда\s+(?:можно|свободн\w*|есть)|"
    r"каки[ем]\s+(?:дат\w*|дни|числ\w*)\s+свободн\w*",
    re.IGNORECASE,
)

# Конкретная календарная дата: 01.09, «1 сентября», «5-6 сентября».
#
# ТИРЕ РАЗБИРАЕТСЯ ОСТОРОЖНЕЕ ТОЧКИ. «6-8» — это и «6-8 сентября», и «нас
# будет 6-8 человек», и «на 2-3 часа». Первое — дата, остальные — нет, а
# прежняя редакция считала датой всё подряд: «сколько стоит?» с историей
# «нас будет 6-8 человек» включала принуждение цены, приняв количество
# гостей за число месяца.
#
# Точка и слэш такой двусмысленности не создают (никто не пишет «6.8
# человек»), поэтому оговорка висит только на тире.
CONCRETE_DATE = re.compile(
    r"\b\d{1,2}\s*[./]\s*\d{1,2}(?:\s*[./]\s*\d{2,4})?\b|"
    r"\b\d{1,2}\s*[-–—]\s*\d{1,2}\b(?!\s*(?:чел|гост|персон|час|шт|мин))|"
    r"\b\d{1,2}\s+(?:январ|феврал|март|апрел|ма[йя]|июн|июл|август|"
    r"сентябр|октябр|ноябр|декабр)\w*",
    re.IGNORECASE,
)

# Относительный день или день недели — дата есть, но её надо разобрать.
RELATIVE_DATE = re.compile(
    r"\b(?:сегодня|завтра|послезавтра|выходны\w*|"
    r"понедельник\w*|вторник\w*|сред[ауы]|четверг\w*|пятниц\w*|"
    r"суббот\w*|воскресень\w*)\b",
    re.IGNORECASE,
)

# Время: «16 00», «16:00», «в 16», «на 4 часа», «вечером».
TIME_SIGNAL = re.compile(
    r"\b\d{1,2}\s*[:.\s]\s*\d{2}\b|\bв\s+\d{1,2}\b|\bна\s+\d{1,2}\s*час\w*|"
    r"\b\d{1,2}\s*час\w*|\bутр\w*|\bвечер\w*|\bдн[ёе]м\b|\bночью\b",
    re.IGNORECASE,
)


def price_slot_known(context: str) -> bool:
    """Названа ли в разговоре зона или дата — то, без чего цены не бывает.

    ЗАЧЕМ. `calculate_price` требует `zone_id` и `date`. Принуждать его на
    «а цена какая?», когда клиент не сказал ни того, ни другого, — значит
    заставить модель выдумать оба поля, получить в ответ `needs_input` и
    следом спросить у клиента всё разом. Замер 2026-09-02: доля ответов
    больше чем с одним вопросом выросла с 2% до 18% именно на этом.

    Дата ИЛИ зона, а не обе: одной уже хватает, чтобы вызов был осмысленным,
    а второе поле модель спросит одним вопросом.
    """
    return bool(
        ZONE_WORDS.search(context)
        or CONCRETE_DATE.search(context)
        or RELATIVE_DATE.search(context)
    )


def forced_tool_for(client_text: str, context: str = "") -> Optional[str]:
    """Имя инструмента, который обязан быть вызван, либо None.

    `context` — то, что клиент уже сказал в этом разговоре (и зона из
    объявления, если она однозначно разобралась). ТОЛЬКО его сторона: в
    приветствии агента перечислены все зоны разом, и считать это за
    «клиент назвал зону» значит не считать вообще ничего.

    Порядок веток — часть поведения:

      0. сообщение вообще не про запись     -> None (вето, см. NOT_A_BOOKING)
      1. спросили цену И зона/дата известны -> calculate_price
      2. есть дата И время вместе           -> check_availability
      3. спросили «когда ближайшее»         -> find_next_available
      4. дальше — только при признаке записи:
         конкретная дата или время          -> check_availability
         относительная дата                 -> resolve_date

    ПОРЯДОК ЗДЕСЬ ОПИСАН ТОТ, ЧТО В КОДЕ. Прежний докстринг обещал «ни одна
    ветка не срабатывает без признака доступности», а ветки 2 и 3 стояли до
    этой проверки — и обещание было неправдой ровно там, где оно важно.
    Ветка 2 признака не требует НАМЕРЕННО: второй ход инцидента 2026-09-01
    выглядел как «сегодня 16 00», признак остался в предыдущей реплике.
    Отсюда и вето нулевой ветки: без него та же ветка ходила в календарь на
    «завтра перезвоню в 5» и на прошедший визит.

    Возврат None означает «не принуждать» — модель решает сама, как и
    раньше. Это НЕ значит «инструмент не нужен»: последний рубеж в
    app/agent/loop.py всё равно не выпустит выдуманную занятость.
    """
    text = client_text or ""
    if not text.strip():
        return None

    # Вето: обещание перезвонить, прошедший визит, отмена.
    if NOT_A_BOOKING.search(text):
        return None

    # Цена — первая ветка, но НЕ безусловная: без зоны и без даты
    # calculate_price нечем звать (см. price_slot_known). И НЕ короткое
    # замыкание: раньше «Сколько стоит? И есть окошко?» возвращало None,
    # потому что ценовая ветка проглатывала ход целиком, так и не дойдя до
    # веток занятости. Не сложилось с ценой — идём дальше.
    if PRICE_ASK.search(text) and price_slot_known(f"{text}\n{context}"):
        return "calculate_price"

    asks_availability = bool(AVAILABILITY_ASK.search(text))
    asks_nearest = bool(NEAREST_ASK.search(text))
    has_date = bool(CONCRETE_DATE.search(text) or RELATIVE_DATE.search(text))
    has_time = bool(TIME_SIGNAL.search(text))

    # ДАТА И ВРЕМЯ ВМЕСТЕ — ЭТО УЖЕ ОТВЕТ ПРО СЛОТ, слово «свободно» в нём не
    # обязано быть. Второй ход инцидента 2026-09-01 выглядел буквально так:
    # «сегодня 16 00» — клиент отвечал на вопрос агента, и признак
    # доступности остался в ПРЕДЫДУЩЕЙ реплике. Без этой ветки принуждение
    # не сработало бы ровно там, где инцидент и продолжился.
    #
    # «Завтра перезвоню» сюда не попадает: времени в нём нет. «Завтра в 5
    # перезвоню» попадёт и стоит одного лишнего вызова календаря — цена
    # приемлемая по сравнению с выдуманной занятостью.
    if has_date and has_time:
        return "check_availability"

    if asks_nearest and not CONCRETE_DATE.search(text):
        # «когда ближайшее свободное» — числа нет, спрашивать его у клиента
        # не надо, на то и инструмент.
        return "find_next_available"

    if not (asks_availability or asks_nearest):
        return None

    if CONCRETE_DATE.search(text) or has_time:
        return "check_availability"

    if RELATIVE_DATE.search(text):
        # «есть окошко завтра?» — сначала превратить «завтра» в дату, и
        # только потом идти в календарь. Считать это в уме модели нельзя:
        # ровно на этом она ошиблась 31 августа и 1 сентября.
        return "resolve_date"

    return None
