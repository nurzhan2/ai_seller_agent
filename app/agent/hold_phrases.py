"""Рубеж «бот не бронирует на словах».

Живые случаи октября 2026: «мы пока придержим для вас время на 17 октября»,
«Оформляю бронь на 24 октября к 12:00», «буду ждать вас 24 октября к
12:00». В YCLIENTS при этом ничего не стояло — бронь ставит менеджер после
предоплаты, — и время спокойно продавали другому клиенту. Промт это уже
запрещает, но промт модель исполняет через раз; здесь — код.

Предложение с таким обещанием вырезается, вместо него — одна честная
фраза. Весь ответ не подменяется: в нём обычно есть цена и вопрос, которые
клиенту нужны.
"""

from __future__ import annotations

import re

FALSE_HOLD = re.compile(
    r"придерж\w*"
    r"|держ(у|им|ать)\s+(для\s+вас|за\s+вами)"
    r"|оформля\w*\s+(вам\s+|для\s+вас\s+)?брон\w*"
    r"|брон\w*\s+(уже\s+)?(оформлен\w*|подтвержден\w*|поставлен\w*|за\s+вами)"
    r"|забронировал\w*"
    r"|место\s+за\s+вами"
    r"|(буд\w+|жд\w+)\s+(ждать\s+)?вас[^.!?\n]{0,40}\b\d{1,2}([:.]\d{2})?\b",
    re.IGNORECASE,
)

HONEST_LINE = (
    "Сейчас это время свободно, бронь подтверждается после предоплаты — "
    "оформит менеджер."
)

_SENTENCE = re.compile(r"[^.!?\n]+[.!?]*\s*|\n")


def strip_false_holds(text: str) -> tuple[str, bool]:
    """(текст без обещаний брони, были ли они)."""
    if not text or not FALSE_HOLD.search(text):
        return text, False
    parts = _SENTENCE.findall(text)
    kept = [p for p in parts if not FALSE_HOLD.search(p)]
    body = "".join(kept).strip()
    body = re.sub(r"\n{3,}", "\n\n", body)
    if HONEST_LINE not in body:
        body = f"{body}\n\n{HONEST_LINE}".strip()
    return body, True
