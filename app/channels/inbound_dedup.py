"""Дедупликация входящих — ОДНА на все каналы приёма.

Раньше жила внутри HTTP-обработчика вебхука (`app/webhooks.py`), и пока канал
был один, разницы не было. С появлением поллера (`app/avito/poller.py`) она
стала неверной по месту: поллер зовёт конвейер напрямую и мимо вебхука, то
есть мимо проверки. Тот же приём, что у `app/channels/outbound_gate.py` и
`app/pricing/quote_gate.py` — инвариант, который обязан выполняться ВЕЗДЕ,
живёт на границе, а не переписывается в каждом вызывающем месте.

САМ КЛЮЧ ПРОВЕРЕН ЖИВЬЁМ. `avito:seen_message:{message_id}` разводит каналы
только если вебхук и `GET /messenger/v3/.../messages/` называют одно и то же
сообщение одним и тем же идентификатором — в спеке это нигде не обещано.
Сверка на аккаунте заказчика (scripts/poll_once.py --check-ids, 6 чатов,
формат 32 hex-символа) показала, что совпадают. Если Авито это когда-нибудь
изменит, чинить надо здесь, и составной ключ (chat_id + created + хеш
текста) — известный запасной вариант.

ТРИ ОПЕРАЦИИ ВМЕСТО ОДНОЙ, И ЭТО ГЛАВНОЕ ЗДЕСЬ. Простой `SET NX` на длинный
срок ТЕРЯЕТ СООБЩЕНИЯ: ключ ставится до обработки, обработка падает, курсор
поллера не двигается, следующий проход достаёт то же сообщение снова — и
молча отбрасывает его как дубль. Сообщение исчезает без следа, а снаружи это
выглядит как «клиент написал, агент промолчал».

Поэтому заявка ставится НА МИНУТУ (`claim`), и только после того, как
конвейер её принял, срок продлевается до суток (`confirm`). Упала обработка —
заявка снимается сразу (`release`). Убили процесс так, что не отработал даже
`finally`, — заявка истечёт сама через минуту, и следующий проход поллера
подберёт сообщение.
"""

from __future__ import annotations

import logging
from typing import Any, Optional

logger = logging.getLogger("parmangal.dedup")

SEEN_KEY = "avito:seen_message:{message_id}"

# Сколько живёт заявка до подтверждения. Верхняя граница времени, на которое
# сообщение «застревает» после жёсткого убийства процесса: меньше — риск, что
# два воркера возьмут одно сообщение, пока первый ещё работает; больше —
# дольше молчание после аварии. Минута с запасом покрывает приём (запись в
# БД и постановку в debounce), но не сам ход агента — он и не должен сюда
# входить, см. докстринг модуля.
PROVISIONAL_TTL_SECONDS = 60


async def claim(message_id: Optional[str], redis: Any) -> bool:
    """True — сообщение наше, обрабатываем. False — его уже взяли.

    Атомарность даёт SET NX: два воркера, получившие один и тот же ретрай (или
    вебхук и поллер одновременно), состязаются на одной операции, и выигрывает
    ровно один.

    Без Redis (redis=None) заявка выдаётся всегда — так же, как раньше вёл
    себя `is_duplicate`. Это не «дедупа нет»: остаётся уникальный индекс
    `uq_messages_avito_message_id`, он не даст сохранить текст дважды. Чего он
    не закрывает — сообщения БЕЗ текста: строки в `messages` для них нет, и
    шаблонный ответ на фото без Redis может уйти дважды.
    """
    # Нечем дедуплицировать (Авито не прислало id) или негде (нет Redis) —
    # ОБРАБАТЫВАЕМ. Ровно то же решение, что принимал прежний `is_duplicate`,
    # возвращая False. Обратное означало бы, что сообщение без идентификатора
    # молча исчезает, — худшая из возможных трактовок неизвестности.
    if message_id is None or redis is None:
        return True
    key = SEEN_KEY.format(message_id=message_id)
    was_set = await redis.set(key, "1", nx=True, ex=PROVISIONAL_TTL_SECONDS)
    return bool(was_set)


async def confirm(message_id: Optional[str], redis: Any, ttl_seconds: int) -> None:
    """Сообщение принято — продлить заявку на полный срок.

    Без NX: ключ уже наш, и его надо ПЕРЕЗАПИСАТЬ с длинным сроком, а не
    поставить заново.
    """
    if message_id is None or redis is None:
        return
    await redis.set(SEEN_KEY.format(message_id=message_id), "1", ex=ttl_seconds)


async def release(message_id: Optional[str], redis: Any) -> None:
    """Обработка не состоялась — снять заявку, чтобы сообщение вернулось.

    Ошибка снятия глотается намеренно: она означает лишь, что сообщение
    подождёт истечения минутного срока, и ронять из-за этого обработку (а
    вызывают release из `finally`, поверх уже случившегося исключения)
    значило бы подменить настоящую причину сбоя вторичной.
    """
    if message_id is None or redis is None:
        return
    try:
        await redis.delete(SEEN_KEY.format(message_id=message_id))
    except Exception:
        logger.warning(
            "dedup: не удалось снять заявку, сообщение подождёт %d с",
            PROVISIONAL_TTL_SECONDS,
            extra={"message_id": message_id},
        )
