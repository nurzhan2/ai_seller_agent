"""Единственный источник «который час» и «какое сегодня число».

ПОВОД. Инцидент 2026-08-31: клиент просил записать его на сегодня, агент
сначала предложил этот день как свободный, потом ответил «сегодняшняя дата
уже прошла», потом снова предложил — и так по кругу. Разбор показал две
разные болезни одного корня: моделью дата бралась из воздуха (в промте её
не было вовсе), а кодом — из `date.today()`, то есть по UTC, тогда как
бизнес живёт по Москве.

ПОЧЕМУ МОСКВА, А НЕ UTC. Всё, что агент говорит клиенту про даты и время,
— это московские сутки: «сегодня», «завтра», «с 14:00», будни против
выходных, окно работы 9:00–23:00. Хранить и сравнивать метки времени в UTC
правильно, но ОТВЕЧАТЬ на вопрос «какое сегодня число» обязано московское
время. Разница в три часа означает, что с 00:00 до 03:00 МСК контейнер
считает вчерашний день сегодняшним: клиент в час ночи просит «на сегодня»,
а получает вчера.

ПОЧЕМУ ФИКСИРОВАННЫЙ СДВИГ, А НЕ zoneinfo("Europe/Moscow"). Россия не
переходит на летнее время с 2014 года, а zoneinfo на python:3.12-slim
требует отдельно поставленного пакета tzdata — лишняя зависимость ради
того, что и так не меняется. Раньше та же константа была объявлена ДВАЖДЫ
(app/dialog_store.py и app/channels/daily_limit.py); теперь она здесь одна,
и остальные импортируют её отсюда.
"""

from __future__ import annotations

from datetime import date as DateType, datetime, timedelta, timezone

MOSCOW_TZ = timezone(timedelta(hours=3), name="MSK")

# Дни недели по-русски — для строки текущей даты в системном промте.
WEEKDAYS_RU = (
    "понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье",
)


def moscow_now() -> datetime:
    """Текущий момент в московском поясе (aware datetime)."""
    return datetime.now(timezone.utc).astimezone(MOSCOW_TZ)


def moscow_today() -> DateType:
    """Сегодняшнее число ПО МОСКВЕ.

    Именно это, а не `date.today()`, должно стоять везде, где решается
    «дата в прошлом», «сегодня/завтра» и с какого дня искать свободные
    окна: клиент и администратор смотрят на московский календарь.
    """
    return moscow_now().date()


def describe_now(now: datetime | None = None) -> str:
    """Человеческая строка «сегодня такое-то число, такой-то день, время».

    Уходит в системный промт. Без неё модель берёт дату из собственных
    представлений — ровно то, из-за чего 31 августа было названо сначала
    «завтра», потом «сегодня», а потом «уже прошло».
    """
    moment = (now or moscow_now()).astimezone(MOSCOW_TZ)
    return (
        f"{moment.strftime('%d.%m.%Y')} ({WEEKDAYS_RU[moment.weekday()]}), "
        f"время {moment.strftime('%H:%M')} МСК"
    )
